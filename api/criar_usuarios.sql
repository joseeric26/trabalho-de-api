CREATE TABLE IF NOT EXISTS usuarios (
    -- O PostgreSQL gera o ID de cada cadastro.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- NOT NULL exige um valor para estas colunas.
    nome TEXT NOT NULL,
    email TEXT NOT NULL,

    -- Impede que dois registros tenham o mesmo e-mail.
    CONSTRAINT uk_usuarios_email UNIQUE (email)
);